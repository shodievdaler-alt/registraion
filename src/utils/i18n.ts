export class I18nService {
  private currentLang: SupportedLanguage = 'ru';
  private listeners: Array<(lang: SupportedLanguage) => void> = [];

  constructor() {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('avz_lang') as SupportedLanguage;
      if (saved && TRANSLATIONS[saved]) {
        this.currentLang = saved;
      }
    }
  }

  public getLanguage(): SupportedLanguage {
    return this.currentLang;
  }

  public setLanguage(lang: SupportedLanguage) {
    this.currentLang = lang;
    if (typeof window !== 'undefined') {
      localStorage.setItem('avz_lang', lang);
    }
    this.listeners.forEach(fn => fn(lang));
  }

  public subscribe(fn: (lang: SupportedLanguage) => void): () => void {
    this.listeners.push(fn);
    return () => {
      this.listeners = this.listeners.filter(l => l !== fn);
    };
  }

  public t(key: string): string {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.ru;
    return dict[key] || TRANSLATIONS.ru[key] || key;
  }
}

export const i18n = new I18nService();

import { useState, useEffect } from 'react';

export function useTranslation() {
  const [lang, setLang] = useState<SupportedLanguage>(() => i18n.getLanguage());

  useEffect(() => {
    return i18n.subscribe((newLang) => {
      setLang(newLang);
    });
  }, []);

  return {
    lang,
    setLanguage: (l: SupportedLanguage) => i18n.setLanguage(l),
    t: (key: string) => i18n.t(key),
  };
}
